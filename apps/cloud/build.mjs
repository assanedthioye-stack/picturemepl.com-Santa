// Bundles the API into a single Supabase Edge Function (Deno). The Postgres driver stays an npm: import.
import { build } from 'esbuild';

await build({
  entryPoints: ['src/edge.ts'],
  outfile: '../../supabase/functions/api/index.js',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  conditions: ['import', 'module', 'default'],
  logLevel: 'info',
  plugins: [{
    name: 'deno-npm',
    setup(b) {
      b.onResolve({ filter: /^postgres$/ }, () => ({ path: 'npm:postgres@3.4.9', external: true }));
    },
  }],
  banner: { js: '// Generated by apps/cloud/build.mjs — do not edit. Deploy: supabase functions deploy api --no-verify-jwt' },
});
